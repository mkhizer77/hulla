/* Generates thulla/traceability.md; with --check exits 1 when an engine-scope id has no vector or no test. */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface RuleId {
  readonly id: string;
  readonly title: string;
  readonly scope: "engine" | "table-core" | "client" | "later";
  readonly vectorable?: boolean;
}

const packageRoot = join(import.meta.dirname, "..");
const repoRoot = join(packageRoot, "..", "..");
const catalogue = JSON.parse(
  readFileSync(join(packageRoot, "thulla", "rule-ids.json"), "utf8"),
) as {
  ids: RuleId[];
};

const vectorsById = new Map<string, string[]>();
const vectorFiles = readdirSync(join(packageRoot, "thulla")).filter(
  (n) => n.startsWith("V-") && n.endsWith(".json"),
);
for (const name of vectorFiles) {
  const vector = JSON.parse(readFileSync(join(packageRoot, "thulla", name), "utf8")) as {
    id: string;
    rules: string[];
  };
  for (const id of vector.rules) {
    vectorsById.set(id, [...(vectorsById.get(id) ?? []), vector.id]);
  }
}

function walk(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === "dist" || entry === "coverage") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (full.endsWith(".test.ts")) out.push(full);
  }
}
const testFiles: string[] = [];
walk(join(repoRoot, "packages"), testFiles);

const testsById = new Map<string, string[]>();
for (const file of testFiles) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(/\bit\(\s*["'`]([^"'`]+)["'`]/g)) {
    const name = match[1] ?? "";
    for (const id of new Set(name.match(/(?<![A-Za-z0-9])[RE]\d+(?!\d)/g) ?? [])) {
      testsById.set(id, [...(testsById.get(id) ?? []), name]);
    }
  }
}

const lines: string[] = [
  "# Thulla traceability",
  "",
  "Generated by `scripts/traceability.ts`; do not edit. Every engine-scope id needs at least one vector and one test whose name carries it; table-core and client ids are covered when those layers land (M1), later ids with their milestone.",
  "",
  "| ID | Title | Scope | Vectors | Tests |",
  "|---|---|---|---|---|",
];
const gaps: string[] = [];
let engineIds = 0;
let engineCovered = 0;
for (const rule of catalogue.ids) {
  const vectors = vectorsById.get(rule.id) ?? [];
  const tests = testsById.get(rule.id) ?? [];
  const needsVector = rule.scope === "engine" && rule.vectorable !== false;
  const needsTest = rule.scope === "engine";
  if (rule.scope === "engine") {
    engineIds += 1;
    const ok = (!needsVector || vectors.length > 0) && (!needsTest || tests.length > 0);
    if (ok) engineCovered += 1;
    else gaps.push(`${rule.id}: ${vectors.length} vectors, ${tests.length} tests`);
  }
  const shown = vectors.slice(0, 3).join(", ") + (vectors.length > 3 ? ", …" : "");
  const vectorCell =
    vectors.length > 0 ? `${vectors.length} (${shown})` : needsVector ? "none" : "n/a";
  const testCell = tests.length > 0 ? `${tests.length}` : needsTest ? "none" : "n/a";
  lines.push(`| ${rule.id} | ${rule.title} | ${rule.scope} | ${vectorCell} | ${testCell} |`);
}
lines.push(
  "",
  `Engine scope: ${engineCovered} of ${engineIds} ids covered. ${vectorFiles.length} vectors reference ${vectorsById.size} ids.`,
  "",
);
writeFileSync(join(packageRoot, "thulla", "traceability.md"), lines.join("\n"));
console.log(`traceability: engine ${engineCovered}/${engineIds}, gaps ${gaps.length}`);
if (process.argv.includes("--check") && gaps.length > 0) {
  for (const gap of gaps) console.error(`  missing: ${gap}`);
  process.exit(1);
}
