/* Generates <game>/traceability.md for every game; with --check exits 1 when an engine-scope id has no vector or no test. */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface RuleId {
  readonly id: string;
  readonly title: string;
  readonly scope: "engine" | "table-core" | "client" | "later";
  readonly vectorable?: boolean;
}

interface Game {
  readonly dir: string;
  readonly title: string;
  /** Finds this game's rule ids in a test name. */
  readonly ids: RegExp;
  readonly note: string;
}

const GAMES: readonly Game[] = [
  {
    dir: "thulla",
    title: "Thulla",
    ids: /(?<![A-Za-z0-9])[RE]\d+(?!\d)/g,
    note: "table-core and client ids are covered when those layers land (M1), later ids with their milestone.",
  },
  {
    dir: "rung",
    title: "Rung",
    ids: /(?<![A-Za-z0-9])RGE?\d+(?!\d)/g,
    note: "table-core ids are covered with the shell changes, later ids with the bots.",
  },
];

const packageRoot = join(import.meta.dirname, "..");
const repoRoot = join(packageRoot, "..", "..");

function walk(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === "dist" || entry === "coverage") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (full.endsWith(".test.ts")) out.push(full);
  }
}
const testFiles: string[] = [];
walk(join(repoRoot, "packages"), testFiles);
const testNames: string[] = [];
for (const file of testFiles) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(/\bit\(\s*["'`]([^"'`]+)["'`]/g)) {
    testNames.push(match[1] ?? "");
  }
}

/** Writes one game's matrix and returns its gaps. */
function trace(game: Game): string[] {
  const dir = join(packageRoot, game.dir);
  const catalogue = JSON.parse(readFileSync(join(dir, "rule-ids.json"), "utf8")) as {
    ids: RuleId[];
  };

  const vectorsById = new Map<string, string[]>();
  const vectorFiles = readdirSync(dir).filter((n) => n.startsWith("V-") && n.endsWith(".json"));
  for (const name of vectorFiles) {
    const vector = JSON.parse(readFileSync(join(dir, name), "utf8")) as {
      id: string;
      rules: string[];
    };
    for (const id of vector.rules) {
      vectorsById.set(id, [...(vectorsById.get(id) ?? []), vector.id]);
    }
  }

  const testsById = new Map<string, string[]>();
  for (const name of testNames) {
    for (const id of new Set(name.match(game.ids) ?? [])) {
      testsById.set(id, [...(testsById.get(id) ?? []), name]);
    }
  }

  const lines: string[] = [
    `# ${game.title} traceability`,
    "",
    `Generated by \`scripts/traceability.ts\`; do not edit. Every engine-scope id needs at least one vector and one test whose name carries it; ${game.note}`,
    "",
    "| ID | Title | Scope | Vectors | Tests |",
    "|---|---|---|---|---|",
  ];
  const gaps: string[] = [];
  let engineIds = 0;
  let engineCovered = 0;
  for (const rule of catalogue.ids) {
    const vectors = vectorsById.get(rule.id) ?? [];
    const tests = testsById.get(rule.id) ?? [];
    const needsVector = rule.scope === "engine" && rule.vectorable !== false;
    const needsTest = rule.scope === "engine";
    if (rule.scope === "engine") {
      engineIds += 1;
      const ok = (!needsVector || vectors.length > 0) && (!needsTest || tests.length > 0);
      if (ok) engineCovered += 1;
      else gaps.push(`${rule.id}: ${vectors.length} vectors, ${tests.length} tests`);
    }
    const shown = vectors.slice(0, 3).join(", ") + (vectors.length > 3 ? ", …" : "");
    const vectorCell =
      vectors.length > 0 ? `${vectors.length} (${shown})` : needsVector ? "none" : "n/a";
    const testCell = tests.length > 0 ? `${tests.length}` : needsTest ? "none" : "n/a";
    lines.push(`| ${rule.id} | ${rule.title} | ${rule.scope} | ${vectorCell} | ${testCell} |`);
  }
  lines.push(
    "",
    `Engine scope: ${engineCovered} of ${engineIds} ids covered. ${vectorFiles.length} vectors reference ${vectorsById.size} ids.`,
    "",
  );
  writeFileSync(join(dir, "traceability.md"), lines.join("\n"));
  console.log(
    `traceability ${game.dir}: engine ${engineCovered}/${engineIds}, gaps ${gaps.length}`,
  );
  return gaps;
}

const gaps = GAMES.flatMap((game) => trace(game).map((gap) => `${game.dir} ${gap}`));
if (process.argv.includes("--check") && gaps.length > 0) {
  for (const gap of gaps) console.error(`  missing: ${gap}`);
  process.exit(1);
}
