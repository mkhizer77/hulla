import type { JsonSchema } from "./schemas";

/** One event parameter as the generators see it. */
interface Param {
  readonly name: string;
  readonly kind: "string" | "integer" | "number" | "boolean";
  readonly values: readonly string[] | null;
  readonly required: boolean;
}

interface EventDef {
  readonly name: string;
  readonly params: readonly Param[];
}

/** Reads schemas/analytics/events.json into a list of events with typed parameters. */
export function analyticsEvents(schema: JsonSchema): readonly EventDef[] {
  const definitions = (schema["definitions"] ?? {}) as Record<string, JsonSchema>;
  return Object.entries(definitions).map(([name, def]) => {
    const props = (def["properties"] ?? {}) as Record<string, JsonSchema>;
    const required = new Set((def["required"] ?? []) as string[]);
    return {
      name,
      params: Object.entries(props).map(([param, p]) => ({
        name: param,
        kind: p["type"] as Param["kind"],
        values: Array.isArray(p["enum"]) ? (p["enum"] as string[]) : null,
        required: required.has(param),
      })),
    };
  });
}

function pascal(name: string): string {
  return name
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function camel(name: string): string {
  const p = pascal(name);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

function tsType(param: Param): string {
  if (param.values !== null) return param.values.map((v) => JSON.stringify(v)).join(" | ");
  return param.kind === "integer" || param.kind === "number" ? "number" : param.kind;
}

/** TypeScript: the event map for server emitters, so names and parameters can't drift (ARCHITECTURE 12.4). */
export function generateAnalyticsTs(events: readonly EventDef[]): string {
  const lines = [
    "/* Generated by tools/codegen from packages/protocol/schemas/analytics/events.json. Do not edit. */",
    "",
    "/** Every analytics event (GDD 23.3) and its parameters. */",
    "export interface AnalyticsEvents {",
    ...events.flatMap((e) => [
      `  readonly ${e.name}: {`,
      ...e.params.map((p) => `    readonly ${p.name}${p.required ? "" : "?"}: ${tsType(p)};`),
      "  };",
    ]),
    "}",
    "",
    "export type AnalyticsEventName = keyof AnalyticsEvents;",
    "",
    "export const ANALYTICS_EVENT_NAMES: readonly AnalyticsEventName[] = [",
    ...events.map((e) => `  ${JSON.stringify(e.name)},`),
    "];",
    "",
  ];
  return lines.join("\n");
}

function csType(param: Param): string {
  const base =
    param.kind === "integer"
      ? "long"
      : param.kind === "number"
        ? "double"
        : param.kind === "boolean"
          ? "bool"
          : "string";
  return param.required ? base : `${base}?`;
}

/** C#: one builder per event with typed arguments; optional parameters are left out when null. */
export function generateAnalyticsCs(events: readonly EventDef[]): string {
  const lines = [
    "// <auto-generated />",
    "// Generated by tools/codegen from packages/protocol/schemas/analytics/events.json. Do not edit.",
    "#nullable enable",
    "namespace Hulla.Protocol",
    "{",
    "    using System.Collections.Generic;",
    "",
    "    /// <summary>An analytics event: a name from GDD 23.3 and its parameters, never names, chat or cards.</summary>",
    "    public sealed class AnalyticsEvent",
    "    {",
    "        public AnalyticsEvent(string name, IReadOnlyDictionary<string, object> parameters)",
    "        {",
    "            Name = name;",
    "            Parameters = parameters;",
    "        }",
    "",
    "        public string Name { get; }",
    "",
    "        public IReadOnlyDictionary<string, object> Parameters { get; }",
    "    }",
    "",
    "    public static class AnalyticsEvents",
    "    {",
  ];
  events.forEach((e, index) => {
    const args = [...e.params]
      .sort((a, b) => Number(b.required) - Number(a.required))
      .map((p) => `${csType(p)} ${camel(p.name)}${p.required ? "" : " = null"}`);
    if (index > 0) lines.push("");
    lines.push(`        public static AnalyticsEvent ${pascal(e.name)}(${args.join(", ")})`);
    lines.push("        {");
    lines.push("            var p = new Dictionary<string, object>();");
    for (const p of e.params) {
      const arg = camel(p.name);
      if (p.values !== null) {
        lines.push(`            // ${p.name}: ${p.values.join(", ")}`);
      }

      if (p.required) {
        lines.push(`            p["${p.name}"] = ${arg};`);
      } else {
        lines.push(`            if (${arg} != null) p["${p.name}"] = ${arg};`);
      }
    }

    lines.push(`            return new AnalyticsEvent("${e.name}", p);`);
    lines.push("        }");
  });
  lines.push("    }", "}", "");
  return lines.join("\n");
}
