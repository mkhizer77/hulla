import AjvDraft7 from "ajv";
import standaloneCode from "ajv/dist/standalone";

import { PROTOCOL_BASE, entryRef, type JsonSchema, type OpcodeEntry } from "./schemas";

const BANNER = "/* Generated by tools/codegen from packages/protocol/schemas. Do not edit. */";

/**
 * Plain validation functions compiled ahead of time (ADR-0022): no schema compiler and no class
 * machinery at runtime, so they run inside Nakama's JavaScript engine. The zod validators next to
 * them serve the web client, where a typed parse is worth the weight.
 */
export function generateChecks(
  opcodes: readonly OpcodeEntry[],
  byId: Map<string, JsonSchema>,
): string {
  const ajv = new AjvDraft7({
    schemas: [...byId.values()],
    code: { source: true, esm: true, lines: true },
    strictRequired: false,
    allowUnionTypes: true,
    unicodeRegExp: false,
    // Count string lengths in UTF-16 units like the web client; keeps the output free of helpers.
    unicode: false,
    messages: false,
  });
  const mapping: Record<string, string> = {
    check_envelope: `${PROTOCOL_BASE}envelope.json`,
    check_rules_selection: `${PROTOCOL_BASE}shell/table.json#/definitions/rulesSelection`,
    check_thulla_view: `${PROTOCOL_BASE}games/thulla/views.json#/definitions/view`,
    check_profile: `${PROTOCOL_BASE}shell/profile.json#/definitions/profile`,
    check_profile_update: `${PROTOCOL_BASE}shell/profile.json#/definitions/profile_update`,
    check_profile_get: `${PROTOCOL_BASE}shell/profile.json#/definitions/profile_get`,
  };
  for (const entry of opcodes) {
    mapping[`check_${entry.type}`] = entryRef(entry);
  }
  // Nakama freezes the global object after InitModule, so the validators (which write their
  // `errors` property on every call) are created by a factory at call time, never at load time.
  const code = standaloneCode(ajv, mapping)
    .split("\n")
    .map((line) => (line.startsWith("export const ") ? line.slice("export ".length) : line))
    .join("\n");
  const table = opcodes.map((entry) => `      ${entry.type}: check_${entry.type},`);
  return [
    BANNER,
    "// @ts-nocheck",
    "/* eslint-disable */",
    "",
    "/** `true` when the value matches the schema; the value is left untouched. */",
    "export type Check = (data: unknown) => boolean;",
    "",
    "export interface Checks {",
    "  readonly envelope: Check;",
    "  readonly rulesSelection: Check;",
    "  readonly thullaView: Check;",
    "  readonly profile: Check;",
    "  readonly profileUpdate: Check;",
    "  readonly profileGet: Check;",
    "  /** One check per message type in the opcode table. */",
    "  readonly payload: Readonly<Record<string, Check>>;",
    "}",
    "",
    "/**",
    " * Builds the validators. Call it where they are used (per match or per RPC call): Nakama's",
    " * runtime freezes everything reachable from the global object after InitModule (ADR-0022).",
    " */",
    "export function createChecks(): Checks {",
    code,
    "  return {",
    "    envelope: check_envelope,",
    "    rulesSelection: check_rules_selection,",
    "    thullaView: check_thulla_view,",
    "    profile: check_profile,",
    "    profileUpdate: check_profile_update,",
    "    profileGet: check_profile_get,",
    "    payload: {",
    ...table,
    "    },",
    "  };",
    "}",
    "",
  ].join("\n");
}
