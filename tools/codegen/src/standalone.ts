import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone";

import { PROTOCOL_BASE, entryRef, type JsonSchema, type OpcodeEntry } from "./schemas";

const BANNER = "/* Generated by tools/codegen from packages/protocol/schemas. Do not edit. */";

/**
 * Plain validation functions compiled ahead of time (ADR-0022): no schema compiler and no class
 * machinery at runtime, so they run inside Nakama's JavaScript engine. The zod validators next to
 * them serve the web client, where a typed parse is worth the weight.
 */
export function generateChecks(
  opcodes: readonly OpcodeEntry[],
  byId: Map<string, JsonSchema>,
): string {
  const ajv = new Ajv({
    schemas: [...byId.values()],
    code: { source: true, esm: true, lines: true },
    strictRequired: false,
    allowUnionTypes: true,
    unicodeRegExp: false,
    // Count string lengths in UTF-16 units like the web client; keeps the output free of helpers.
    unicode: false,
    messages: false,
  });
  const mapping: Record<string, string> = {
    check_envelope: `${PROTOCOL_BASE}envelope.json`,
    check_rules_selection: `${PROTOCOL_BASE}shell/table.json#/definitions/rulesSelection`,
    check_thulla_view: `${PROTOCOL_BASE}games/thulla/views.json#/definitions/view`,
  };
  for (const entry of opcodes) {
    mapping[`check_${entry.type}`] = entryRef(entry);
  }
  const code = standaloneCode(ajv, mapping);
  const table = opcodes.map((entry) => `  ${entry.type}: check_${entry.type},`);
  return [
    BANNER,
    "// @ts-nocheck",
    "/* eslint-disable */",
    code,
    "",
    "/** `true` when the value matches the message type's schema; the value is left untouched. */",
    "export type Check = (data: unknown) => boolean;",
    "",
    "export const payloadChecks: Readonly<Record<string, Check>> = {",
    ...table,
    "};",
    "",
  ].join("\n");
}
