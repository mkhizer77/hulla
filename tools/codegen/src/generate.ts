import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { ASMDEF, UPM_PACKAGE, generateCSharp } from "./csharp";
import { buildRoot, loadOpcodes, loadSchemas } from "./schemas";
import { generateOpcodes, generateTypes, generateValidators } from "./typescript";

const protocolDir = join(import.meta.dirname, "..", "..", "..", "packages", "protocol");
const schemasDir = join(protocolDir, "schemas");
const tsDir = join(protocolDir, "generated", "ts");
const csDir = join(protocolDir, "generated", "csharp");
mkdirSync(tsDir, { recursive: true });
mkdirSync(csDir, { recursive: true });

const byId = loadSchemas(schemasDir);
const opcodes = loadOpcodes(schemasDir);
const root = buildRoot(opcodes);

writeFileSync(join(tsDir, "protocol.ts"), await generateTypes(root, byId));
writeFileSync(join(tsDir, "validators.ts"), await generateValidators(opcodes, byId));
writeFileSync(join(tsDir, "opcodes.ts"), generateOpcodes(opcodes));
writeFileSync(
  join(tsDir, "index.ts"),
  [
    "/* Generated by tools/codegen from packages/protocol/schemas. Do not edit. */",
    'export * from "./protocol";',
    'export * from "./validators";',
    'export * from "./opcodes";',
    "",
  ].join("\n"),
);
writeFileSync(join(csDir, "Protocol.cs"), await generateCSharp(root, byId));
writeFileSync(join(csDir, "package.json"), `${JSON.stringify(UPM_PACKAGE, null, 2)}\n`);
writeFileSync(join(csDir, "Hulla.Protocol.asmdef"), `${JSON.stringify(ASMDEF, null, 2)}\n`);
console.log(`codegen: ${opcodes.length} message types → ${tsDir} and ${csDir}`);
