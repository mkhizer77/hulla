import {
  InputData,
  JSONSchemaInput,
  JSONSchemaStore,
  quicktype,
  type JSONSchema,
} from "quicktype-core";

import type { JsonSchema, OpcodeEntry } from "./schemas";

class LocalStore extends JSONSchemaStore {
  constructor(private readonly byId: Map<string, JsonSchema>) {
    super();
  }

  override fetch(address: string): Promise<JSONSchema | undefined> {
    const url = address.split("#")[0] ?? address;
    return Promise.resolve(this.byId.get(url) as JSONSchema | undefined);
  }
}

/** C# DTOs with Newtonsoft.Json attributes and converters, in the Hulla.Protocol namespace. */
export async function generateCSharp(
  root: JsonSchema,
  byId: Map<string, JsonSchema>,
): Promise<string> {
  const input = new JSONSchemaInput(new LocalStore(byId));
  await input.addSource({
    name: "Protocol",
    schema: JSON.stringify(root),
    uris: [String(root["$id"])],
  });
  const inputData = new InputData();
  inputData.addInput(input);
  const result = await quicktype({
    inputData,
    lang: "csharp",
    rendererOptions: {
      namespace: "Hulla.Protocol",
      framework: "NewtonSoft",
      "array-type": "list",
      density: "normal",
      "check-required": "true",
      features: "complete",
    },
  });
  return `${["// <auto-generated />", "// Generated by tools/codegen from packages/protocol/schemas. Do not edit.", ...result.lines].join("\n")}\n`;
}

