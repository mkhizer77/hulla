function pascal(type: string): string {
  return type
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/** The opcode registry for C#: numeric opcodes, wire type names and the lookup between them. */
export function generateCSharpOpcodes(opcodes: readonly OpcodeEntry[]): string {
  const lines = [
    "// <auto-generated />",
    "// Generated by tools/codegen from packages/protocol/schemas/opcodes.json. Do not edit.",
    "#nullable enable",
    "namespace Hulla.Protocol",
    "{",
    "    public static class Opcodes",
    "    {",
    ...opcodes.map((o) => `        public const long ${pascal(o.type)} = ${String(o.opcode)};`),
    "    }",
    "",
    "    public static class MessageTypes",
    "    {",
    ...opcodes.map((o) => `        public const string ${pascal(o.type)} = "${o.type}";`),
    "",
    "        /// <summary>The wire type for an opcode, or null when the opcode is unknown.</summary>",
    "        public static string? ForOpcode(long opcode)",
    "        {",
    "            switch (opcode)",
    "            {",
    ...opcodes.map((o) => `                case ${String(o.opcode)}: return ${pascal(o.type)};`),
    "                default: return null;",
    "            }",
    "        }",
    "",
    "        /// <summary>Public messages advance the table seq; seat and recipient messages carry the current one.</summary>",
    "        public static bool IsPublic(string type)",
    "        {",
    "            switch (type)",
    "            {",
    ...opcodes
      .filter((o) => o.visibility === "public")
      .map((o) => `                case ${pascal(o.type)}:`),
    "                    return true;",
    "                default:",
    "                    return false;",
    "            }",
    "        }",
    "",
    "        /// <summary>The opcode for a wire type, or -1 when the type is unknown.</summary>",
    "        public static long OpcodeFor(string type)",
    "        {",
    "            switch (type)",
    "            {",
    ...opcodes.map(
      (o) => `                case ${pascal(o.type)}: return Opcodes.${pascal(o.type)};`,
    ),
    "                default: return -1;",
    "            }",
    "        }",
    "    }",
    "}",
    "",
  ];
  return lines.join("\n");
}

