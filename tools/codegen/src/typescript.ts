import { dereference } from "@apidevtools/json-schema-ref-parser";
import { compile } from "json-schema-to-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";

import {
  camel,
  entryRef,
  PROTOCOL_BASE,
  resolverFor,
  type JsonSchema,
  type OpcodeEntry,
} from "./schemas";

const BANNER = "/* Generated by tools/codegen from packages/protocol/schemas. Do not edit. */";

export async function generateTypes(
  root: JsonSchema,
  byId: Map<string, JsonSchema>,
): Promise<string> {
  return compile(root, "Protocol", {
    bannerComment: BANNER,
    additionalProperties: false,
    strictIndexSignatures: true,
    $refOptions: { resolve: resolverFor(byId) as never },
    style: { printWidth: 100 },
  });
}

async function dereferenced(ref: string, byId: Map<string, JsonSchema>): Promise<JsonSchema> {
  const [url, pointer] = ref.split("#");
  const schema = byId.get(url ?? "");
  if (schema === undefined) {
    throw new Error(`unknown schema ${ref}`);
  }
  const full = (await dereference(structuredClone(schema) as never, {
    resolve: resolverFor(byId) as never,
  })) as unknown as JsonSchema;
  if (pointer === undefined || pointer === "") {
    return full;
  }
  let node: unknown = full;
  for (const segment of pointer.split("/").filter((s) => s !== "")) {
    node = (node as Record<string, unknown>)[segment];
  }
  return node as JsonSchema;
}

export async function generateValidators(
  opcodes: readonly OpcodeEntry[],
  byId: Map<string, JsonSchema>,
): Promise<string> {
  const lines: string[] = [BANNER, 'import { z } from "zod";', ""];
  const envelope = await dereferenced(`${PROTOCOL_BASE}envelope.json`, byId);
  lines.push(`export const envelopeSchema = ${jsonSchemaToZod(envelope)};`, "");
  const names: string[] = [];
  for (const entry of opcodes) {
    const schema = await dereferenced(entryRef(entry), byId);
    const name = `${camel(entry.type)}PayloadSchema`;
    names.push(`  ${entry.type}: ${name},`);
    lines.push(`export const ${name} = ${jsonSchemaToZod(schema)};`, "");
  }
  lines.push(
    "/** The validator the server runs on every inbound payload, by message type (ARCHITECTURE 8.4). */",
  );
  lines.push("export const payloadValidators = {", ...names, "} as const;", "");
  lines.push("export type MessageType = keyof typeof payloadValidators;", "");
  return lines.join("\n");
}

export function generateOpcodes(opcodes: readonly OpcodeEntry[]): string {
  const rows = opcodes.map(
    (entry) =>
      `  ${entry.type}: { opcode: ${entry.opcode}, direction: "${entry.direction}", visibility: "${entry.visibility}"${entry.game !== undefined ? `, game: "${entry.game}"` : ""} },`,
  );
  return [
    BANNER,
    "/** Every message type with its Nakama opcode, direction and redaction class. */",
    "export const OPCODES = {",
    ...rows,
    "} as const;",
    "",
    "export type OpcodeTable = typeof OPCODES;",
    "",
  ].join("\n");
}
