/* Bundles the runtime modules into one file for Nakama's embedded JS runtime (goja). */
import { build } from "esbuild";

await build({
  entryPoints: ["src/main.ts"],
  bundle: true,
  outfile: "build/index.js",
  format: "cjs",
  platform: "neutral",
  // goja speaks ES5 plus most of ES2015+; newer syntax is lowered, library features must exist in goja.
  target: ["es2015"],
  mainFields: ["module", "main"],
  conditions: ["import", "module", "default"],
  logLevel: "info",
  legalComments: "none",
  banner: { js: "// Hulla runtime modules. Generated by scripts/build.mjs; do not edit." },
});
