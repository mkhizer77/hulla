/* Bundles the runtime modules into one file for Nakama's embedded JS runtime (goja). */
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

import { build } from "esbuild";

/** `file.json?raw` imports the file's exact text, as Vite does in the unit tests. */
const raw = {
  name: "raw",
  setup(b) {
    b.onResolve({ filter: /\?raw$/ }, (args) => ({
      path: resolve(args.resolveDir, args.path.slice(0, -"?raw".length)),
      namespace: "raw",
    }));
    b.onLoad({ filter: /.*/, namespace: "raw" }, async (args) => ({
      contents: await readFile(args.path, "utf8"),
      loader: "text",
    }));
  },
};

await build({
  entryPoints: ["src/main.ts"],
  bundle: true,
  outfile: "build/index.js",
  format: "cjs",
  platform: "neutral",
  // goja speaks ES5 plus most of ES2015+; newer syntax is lowered, library features must exist in goja.
  target: ["es2015"],
  mainFields: ["module", "main"],
  conditions: ["import", "module", "default"],
  logLevel: "info",
  legalComments: "none",
  plugins: [raw],
  banner: { js: "// Hulla runtime modules. Generated by scripts/build.mjs; do not edit." },
});
